#!/usr/bin/env python3
"""Missingness and imputation-flag audit for the natality module.

For every field, year, and population (all records; analytic cohort), counts each
missingness class (O observed, S not stated, A not applicable, I NCHS-imputed,
X invalid). For predictors in the analytic cohort it also reports outcome prevalence
among records with vs without the item, so readers can see whether missingness is
informative. Writes:
    data/processed/missingness_audit.csv
    data/processed/missingness_vs_outcome.csv
    data/processed/qa_report.txt
    docs/MISSINGNESS_AUDIT_NATALITY.md   (rendered from the CSVs, DRAFT-stamped)
    paper/stats.json  [section "audit"]
"""
import sys

import pandas as pd

from natality_common import (OUTCOMES, PROCESSED, ROOT, YEARS, classify, cohort_flow,
                             load_layout, outcome, predictor_rows, update_stats)

CLASSES = ["O", "S", "A", "I", "X"]
FINAL = "--final" in sys.argv   # drop draft banners only after the author's verification


def audit_year(year, lay):
    df = pd.read_parquet(PROCESSED / f"natality_{year}_raw.parquet")
    flow = cohort_flow(df)
    cohort = flow[-1][1]
    rows, inform = [], []
    fields = lay[lay["kind"] != "flag"]
    for pop, mask in [("all", pd.Series(True, index=df.index)), ("cohort", cohort)]:
        sub = df[mask]
        for _, r in fields.iterrows():
            cls = classify(sub, r).value_counts()
            rec = {"year": year, "population": pop, "field": r["name"], "role": r["role"],
                   "n": len(sub)}
            rec.update({c: int(cls.get(c, 0)) for c in CLASSES})
            rows.append(rec)
    sub = df[cohort]
    ys = {t: outcome(sub, t) for t in OUTCOMES}
    pred = lay[lay["role"].isin(["predictor", "pending"])]
    for _, r in pred.iterrows():
        cls = classify(sub, r)
        miss = cls.isin(["S", "I"])
        for t, y in ys.items():
            ok = y.notna()
            inform.append({"year": year, "field": r["name"], "task": t,
                           "n_missing": int((miss & ok).sum()),
                           "prev_missing": y[miss & ok].mean() if (miss & ok).any() else None,
                           "prev_observed": y[~miss & ok].mean()})
    flowcounts = [(name, int(m.sum())) for name, m in flow]
    tasks = {}
    for t, y in ys.items():
        tasks[t] = {"outcome_not_stated": int(y.isna().sum()), "eligible": int(y.notna().sum()),
                    "cases": int(y.sum()), "prevalence": float(y.mean())}
    n_pred = predictor_rows(lay)
    miss_any = pd.concat([classify(sub, r).isin(["S", "I"]) for _, r in n_pred.iterrows()],
                         axis=1).sum(axis=1)
    return (pd.DataFrame(rows), pd.DataFrame(inform), flowcounts, tasks,
            {"any_missing_share": float((miss_any > 0).mean()),
             "mean_missing_items": float(miss_any.mean())})


def fmt(x):
    return f"{100 * x:.2f}%"


def render(aud, inf, flows, tasks, extra, lay):
    lines = ["# Missingness audit — NCHS natality, " + ", ".join(map(str, YEARS)), "",
             ("Generated by `code/03_audit.py` from `data/processed/missingness_audit.csv`." if FINAL else
              "> DRAFT — generated by `code/03_audit.py`; numbers come from "
              "`data/processed/missingness_audit.csv`. Not verified by the author."), "",
             "Classes: **S** not stated · **A** not applicable (structural, not missing) · "
             "**I** imputed by NCHS (restored to missing in the benchmark) · "
             "**X** invalid (should be 0).", "",
             "## Analytic cohort flow", "", "| Stage | " + " | ".join(map(str, YEARS)) + " |",
             "|---|" + "---:|" * len(YEARS)]
    for i, (name, _) in enumerate(flows[YEARS[0]]):
        lines.append(f"| {name} | " + " | ".join(f"{flows[y][i][1]:,}" for y in YEARS) + " |")
    for t, spec in OUTCOMES.items():
        lines.append(f"| {t}: outcome not stated (excluded) | "
                     + " | ".join(f"{tasks[y][t]['outcome_not_stated']:,}" for y in YEARS) + " |")
        lines.append(f"| {t}: eligible / cases / prevalence | " + " | ".join(
            f"{tasks[y][t]['eligible']:,} / {tasks[y][t]['cases']:,} / {fmt(tasks[y][t]['prevalence'])}"
            for y in YEARS) + " |")
    lines += ["", "## Item missingness in the analytic cohort", "",
              "| Field | Role | Label | " + " | ".join(f"{y} S / I / A" for y in YEARS) + " |",
              "|---|---|---|" + "---:|" * len(YEARS)]
    coh = aud[aud["population"] == "cohort"]
    labels = dict(zip(lay["name"], lay["label"]))
    for f in coh["field"].unique():
        cells = []
        for y in YEARS:
            r = coh[(coh["field"] == f) & (coh["year"] == y)].iloc[0]
            cells.append(f"{fmt(r['S']/r['n'])} / {fmt(r['I']/r['n'])} / {fmt(r['A']/r['n'])}")
        lines.append(f"| {f} | {r['role']} | {labels[f]} | " + " | ".join(cells) + " |")
    lines += ["", "## Is missingness informative? (test year " + str(YEARS[-1]) + ")", "",
              "Outcome prevalence among cohort records with the item missing (S or I) vs observed.", "",
              "| Field | Task | n missing | Prevalence if missing | Prevalence if observed |",
              "|---|---|---:|---:|---:|"]
    last = inf[inf["year"] == YEARS[-1]].sort_values(["task", "n_missing"], ascending=[True, False])
    for _, r in last.iterrows():
        if r["n_missing"] == 0:
            continue
        lines.append(f"| {r['field']} | {r['task']} | {r['n_missing']:,} | {fmt(r['prev_missing'])} "
                     f"| {fmt(r['prev_observed'])} |")
    lines += ["", "## Records with any predictor missing", ""]
    for y in YEARS:
        lines.append(f"- {y}: {fmt(extra[y]['any_missing_share'])} of cohort records; "
                     f"mean {extra[y]['mean_missing_items']:.2f} missing predictors per record")
    (ROOT / "docs" / "MISSINGNESS_AUDIT_NATALITY.md").write_text("\n".join(lines) + "\n")


def main():
    lay = load_layout()
    auds, infs, flows, tasks, extra = [], [], {}, {}, {}
    for y in YEARS:
        a, i, f, t, e = audit_year(y, lay)
        auds.append(a); infs.append(i); flows[y] = f; tasks[y] = t; extra[y] = e
    aud, inf = pd.concat(auds), pd.concat(infs)
    aud.to_csv(PROCESSED / "missingness_audit.csv", index=False)
    inf.to_csv(PROCESSED / "missingness_vs_outcome.csv", index=False)
    render(aud, inf, flows, tasks, extra, lay)

    qa = ["PH-MissBench natality QA report" + ("" if FINAL else " (DRAFT)"), ""]
    chk = pd.read_csv(PROCESSED / "layout_check.csv")
    qa.append(f"Layout check: {int(chk['pass'].sum())}/{len(chk)} field-years pass "
              f"(max invalid share {chk['invalid_share'].max():.4%})")
    xbad = aud[aud["X"] > 0]
    qa.append(f"Fields with any invalid codes: {len(xbad)}")
    for _, r in xbad.iterrows():
        qa.append(f"   {r['year']} {r['population']} {r['field']}: {r['X']:,}")
    qa.append("")
    for y in YEARS:
        qa.append(f"{y} cohort flow: " + " -> ".join(f"{n} {c:,}" for n, c in flows[y]))
        for t in OUTCOMES:
            qa.append(f"   {t}: {tasks[y][t]}")
    sanity = []
    for y in YEARS:
        p = tasks[y]["EPTB"]["prevalence"]; v = tasks[y]["VLBW"]["prevalence"]
        sanity.append((f"{y} EPTB prevalence in 0.5%-5%", 0.005 <= p <= 0.05))
        sanity.append((f"{y} VLBW prevalence in 0.3%-3%", 0.003 <= v <= 0.03))
        sanity.append((f"{y} singletons > 90% of residents",
                       flows[y][3][1] / flows[y][1][1] > 0.90))
    qa += ["", "Sanity thresholds:"] + [f"   [{'PASS' if ok else 'FAIL'}] {s}" for s, ok in sanity]
    (PROCESSED / "qa_report.txt").write_text("\n".join(qa) + "\n")
    print("\n".join(qa))

    update_stats("audit", {str(y): {"flow": dict(flows[y]), "tasks": tasks[y], **extra[y]}
                           for y in YEARS})
    if not all(ok for _, ok in sanity) or len(xbad):
        sys.exit("QA flagged problems; read data/processed/qa_report.txt before continuing.")


if __name__ == "__main__":
    main()
